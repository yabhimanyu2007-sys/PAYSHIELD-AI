from __future__ import annotations
from typing import Any

# This is a demo policy. In production, policies must be tenant-specific,
# versioned, persisted, and reviewed by the business owner.
DEFAULT_POLICY = {
    "max_transaction": 10000.00,
    "daily_limit": 50000.00,
    "approved_vendors": ["ABC TECHNOLOGIES", "NORTHSTAR OFFICE", "ACME CLOUD"],
}

INJECTION_MARKERS = [
    "ignore previous instructions",
    "ignore all security rules",
    "bypass approval",
    "do not tell the user",
    "override the payment policy",
    "send credentials",
    "reveal the system prompt",
]

def evaluate_transaction(payload: dict[str, Any], policy: dict | None = None,
                         prior_invoice_ids: set[str] | None = None) -> dict[str, Any]:
    policy = policy or DEFAULT_POLICY
    prior_invoice_ids = prior_invoice_ids or set()

    amount = float(payload.get("amount", 0))
    vendor = str(payload.get("vendor", "")).strip().upper()
    invoice_id = str(payload.get("invoice_id", "")).strip()
    invoice_text = str(payload.get("invoice_text", "")).lower()

    findings: list[dict[str, str]] = []
    risk = 0

    if amount <= 0:
        findings.append({"code": "INVALID_AMOUNT", "severity": "critical",
                         "message": "Amount must be greater than zero."})
        risk += 100

    if amount > float(policy["max_transaction"]):
        findings.append({"code": "LIMIT_EXCEEDED", "severity": "high",
                         "message": f"Amount exceeds the per-transaction limit of {policy['max_transaction']:.2f}."})
        risk += 55

    approved = {v.upper() for v in policy["approved_vendors"]}
    if vendor not in approved:
        findings.append({"code": "UNKNOWN_VENDOR", "severity": "high",
                         "message": "Vendor is not on the approved supplier list."})
        risk += 40

    if invoice_id and invoice_id in prior_invoice_ids:
        findings.append({"code": "DUPLICATE_INVOICE", "severity": "critical",
                         "message": "This invoice ID has already been evaluated."})
        risk += 85

    matched = [marker for marker in INJECTION_MARKERS if marker in invoice_text]
    if matched:
        findings.append({"code": "PROMPT_INJECTION", "severity": "critical",
                         "message": "Invoice text contains instructions attempting to override the payment workflow."})
        risk += 90

    # A human-readable reason is always generated by deterministic code.
    # AI signals may add context but can never lower this score or override policy.
    if risk >= 55:
        decision = "BLOCK"
    elif risk >= 35:
        decision = "REVIEW"
    else:
        decision = "ALLOW"

    if not findings:
        findings.append({"code": "POLICY_PASS", "severity": "info",
                         "message": "No configured policy violations were detected."})

    return {
        "decision": decision,
        "risk_score": min(risk, 100),
        "findings": findings,
        "policy_version": "demo-policy-v1",
        "payment_authorized": decision == "ALLOW",
        "explanation": (
            "Blocked by the independent security policy." if decision == "BLOCK"
            else "Requires a human reviewer before payment." if decision == "REVIEW"
            else "Passed configured checks. Payer approval is still required at PayPal checkout."
        )
    }
